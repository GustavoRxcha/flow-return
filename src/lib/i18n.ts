const DICTIONARIES: Record<Locale, Dictionary> = { pt, en, es }

export type Params = Record<string, string | number>

/** Troca só as chaves informadas: {nome} e outras variáveis de mensagem continuam como estão. */
export function translate(locale: Locale, key: MessageKey, params: Params = {}): string {
  const text = DICTIONARIES[locale][key] ?? pt[key]
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole))
}

type PluralBase<K> = K extends `${infer Base}_one` ? Base : never
export type PluralKey = PluralBase<MessageKey>

/** Português, inglês e espanhol usam singular só para 1. */
export function translatePlural(locale: Locale, key: PluralKey, count: number, params: Params = {}): string {
  const form = (count === 1 ? `${key}_one` : `${key}_other`) as MessageKey
  return translate(locale, form, { n: count, ...params })
}

/** Lista separada por vírgula, como a chave guarda: dias da semana e letras do calendário. */
export function translateList(locale: Locale, key: MessageKey): string[] {
  return translate(locale, key).split(',')
}
